/**
 * Clone production public schema onto test DB (no Docker/pg_dump).
 * Applies DDL in dependency order as whole statements (never splits on ';').
 */
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"
import { createRequire } from "module"

const require = createRequire(import.meta.url)
const { Client } = require("pg")
const { projectRefFromUrl, PRODUCTION_SUPABASE_REF } = require("./verify-env.cjs")

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const outDir = path.join(root, "tmp", "schema-compare")
const reportPath = path.join(outDir, "clone-report.txt")

function parse(file) {
  const out = {}
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/)
    if (!match) continue
    let value = match[2].trim()
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }
    out[match[1]] = value
  }
  return out
}

function qIdent(name) {
  return `"${String(name).replace(/"/g, '""')}"`
}

async function applyStatements(db, label, statements) {
  let ok = 0
  let fail = 0
  const failures = []
  console.log(`\n== ${label} (${statements.length}) ==`)
  for (const sql of statements) {
    if (!sql?.trim()) continue
    try {
      await db.query(sql)
      ok++
    } catch (error) {
      fail++
      const msg = (error.message || String(error)).split("\n")[0]
      failures.push({ msg, preview: sql.slice(0, 160).replace(/\s+/g, " ") })
      if (failures.length <= 25) console.log(`FAIL ${msg}`)
      try {
        await db.query("ROLLBACK")
      } catch {
        /* */
      }
    }
  }
  console.log(`${label}: ${ok} ok, ${fail} failed`)
  return { ok, fail, failures }
}

async function buildPhases(prod) {
  const phases = []

  phases.push({
    label: "extensions",
    statements: ["CREATE EXTENSION IF NOT EXISTS pgcrypto"],
  })

  const enums = await prod.query(`
    SELECT t.typname AS name,
           string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) AS labels
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
    GROUP BY 1
    ORDER BY 1
  `)
  phases.push({
    label: "enums",
    statements: enums.rows.map(
      (row) =>
        `DO $$ BEGIN CREATE TYPE public.${qIdent(row.name)} AS ENUM (${row.labels}); EXCEPTION WHEN duplicate_object THEN NULL; END $$`,
    ),
  })

  const sequences = await prod.query(`
    SELECT c.relname AS name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'S'
    ORDER BY 1
  `)
  phases.push({
    label: "sequences",
    statements: sequences.rows.map(
      (row) => `CREATE SEQUENCE IF NOT EXISTS public.${qIdent(row.name)}`,
    ),
  })

  const tables = await prod.query(`
    SELECT c.relname AS name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
    ORDER BY c.relname
  `)

  const tableStatements = []
  for (const t of tables.rows) {
    const cols = await prod.query(
      `
      SELECT a.attname AS name,
             pg_catalog.format_type(a.atttypid, a.atttypmod) AS typ,
             a.attnotnull AS not_null,
             pg_get_expr(ad.adbin, ad.adrelid) AS default_expr,
             a.attidentity AS identity,
             a.attgenerated AS generated
      FROM pg_attribute a
      JOIN pg_class c ON c.oid = a.attrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
      WHERE n.nspname = 'public' AND c.relname = $1
        AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attnum
    `,
      [t.name],
    )
    const colDefs = cols.rows.map((c) => {
      let def = `${qIdent(c.name)} ${c.typ}`
      if (c.identity === "a") def += " GENERATED ALWAYS AS IDENTITY"
      else if (c.identity === "d") def += " GENERATED BY DEFAULT AS IDENTITY"
      else if (c.generated === "s" && c.default_expr) {
        def += ` GENERATED ALWAYS AS (${c.default_expr}) STORED`
      } else if (c.default_expr) {
        def += ` DEFAULT ${c.default_expr}`
      }
      if (c.not_null) def += " NOT NULL"
      return def
    })
    tableStatements.push(
      `CREATE TABLE IF NOT EXISTS public.${qIdent(t.name)} (\n  ${colDefs.join(",\n  ")}\n)`,
    )
  }
  phases.push({ label: "tables", statements: tableStatements })

  // Functions before check constraints / views that depend on them
  const funcs = await prod.query(`
    SELECT pg_get_functiondef(p.oid) AS def
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.prokind IN ('f','p')
    ORDER BY p.proname, p.oid
  `)
  phases.push({
    label: "functions",
    statements: funcs.rows.map((r) => r.def),
  })

  const puCons = await prod.query(`
    SELECT c.relname AS table_name, con.conname, pg_get_constraintdef(con.oid) AS def
    FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND con.contype IN ('p','u')
    ORDER BY c.relname, con.conname
  `)
  phases.push({
    label: "pk_unique",
    statements: puCons.rows.map(
      (row) =>
        `DO $$ BEGIN ALTER TABLE public.${qIdent(row.table_name)} ADD CONSTRAINT ${qIdent(row.conname)} ${row.def}; EXCEPTION WHEN duplicate_object THEN NULL; END $$`,
    ),
  })

  const checkCons = await prod.query(`
    SELECT c.relname AS table_name, con.conname, pg_get_constraintdef(con.oid) AS def
    FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND con.contype = 'c'
    ORDER BY c.relname, con.conname
  `)
  phases.push({
    label: "checks",
    statements: checkCons.rows.map(
      (row) =>
        `DO $$ BEGIN ALTER TABLE public.${qIdent(row.table_name)} ADD CONSTRAINT ${qIdent(row.conname)} ${row.def}; EXCEPTION WHEN duplicate_object THEN NULL; END $$`,
    ),
  })

  const indexes = await prod.query(`
    SELECT indexdef
    FROM pg_indexes
    WHERE schemaname = 'public'
      AND indexname NOT IN (
        SELECT con.conname
        FROM pg_constraint con
        JOIN pg_class c ON c.oid = con.conrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
      )
    ORDER BY indexname
  `)
  phases.push({
    label: "indexes",
    statements: indexes.rows.map((row) =>
      row.indexdef
        .replace(/^CREATE UNIQUE INDEX /, "CREATE UNIQUE INDEX IF NOT EXISTS ")
        .replace(/^CREATE INDEX /, "CREATE INDEX IF NOT EXISTS "),
    ),
  })

  const fks = await prod.query(`
    SELECT c.relname AS table_name, con.conname, pg_get_constraintdef(con.oid) AS def
    FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND con.contype = 'f'
    ORDER BY c.relname, con.conname
  `)
  phases.push({
    label: "foreign_keys",
    statements: fks.rows.map(
      (row) =>
        `DO $$ BEGIN ALTER TABLE public.${qIdent(row.table_name)} ADD CONSTRAINT ${qIdent(row.conname)} ${row.def}; EXCEPTION WHEN duplicate_object THEN NULL; END $$`,
    ),
  })

  const views = await prod.query(`
    SELECT c.relname AS name, pg_get_viewdef(c.oid, true) AS def, c.relkind
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind IN ('v','m')
    ORDER BY CASE c.relkind WHEN 'v' THEN 0 ELSE 1 END, c.relname
  `)
  // Multiple passes for view dependencies
  const viewStatements = views.rows.map((row) => {
    if (row.relkind === "m") {
      return `CREATE MATERIALIZED VIEW IF NOT EXISTS public.${qIdent(row.name)} AS ${row.def}`
    }
    return `CREATE OR REPLACE VIEW public.${qIdent(row.name)} AS ${row.def}`
  })
  phases.push({ label: "views_pass1", statements: viewStatements })
  // Functions that reference views / other late functions
  phases.push({
    label: "functions_pass2",
    statements: funcs.rows.map((r) => r.def),
  })
  phases.push({ label: "views_pass2", statements: viewStatements })
  phases.push({
    label: "functions_pass3",
    statements: funcs.rows.map((r) => r.def),
  })

  const triggers = await prod.query(`
    SELECT pg_get_triggerdef(t.oid, true) AS def
    FROM pg_trigger t
    JOIN pg_class c ON c.oid = t.tgrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND NOT t.tgisinternal
    ORDER BY c.relname, t.tgname
  `)
  phases.push({
    label: "triggers",
    statements: triggers.rows.map((r) => {
      // pg_get_triggerdef → CREATE TRIGGER ...; make idempotent
      const def = r.def
      const m = def.match(/^CREATE TRIGGER\s+(\S+)\s+ON\s+(\S+)/i)
      if (!m) return def
      return `DROP TRIGGER IF EXISTS ${m[1]} ON ${m[2]};\n${def}`
    }),
  })

  const rls = await prod.query(`
    SELECT c.relname AS name, c.relrowsecurity, c.relforcerowsecurity
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relrowsecurity
    ORDER BY 1
  `)
  phases.push({
    label: "rls_enable",
    statements: rls.rows.flatMap((row) => {
      const out = [`ALTER TABLE public.${qIdent(row.name)} ENABLE ROW LEVEL SECURITY`]
      if (row.relforcerowsecurity) {
        out.push(`ALTER TABLE public.${qIdent(row.name)} FORCE ROW LEVEL SECURITY`)
      }
      return out
    }),
  })

  const policies = await prod.query(`
    SELECT tablename, policyname, permissive, roles, cmd, qual, with_check
    FROM pg_policies
    WHERE schemaname = 'public'
    ORDER BY tablename, policyname
  `)
  function normalizeRoles(roles) {
    if (Array.isArray(roles)) return roles.length ? roles : ["public"]
    if (typeof roles === "string") {
      const inner = roles.replace(/^\{|\}$/g, "").trim()
      if (!inner) return ["public"]
      return inner.split(",").map((s) => s.trim()).filter(Boolean)
    }
    return ["public"]
  }
  phases.push({
    label: "policies",
    statements: policies.rows.map((row) => {
      const roles = normalizeRoles(row.roles)
        .map((r) => (r.toLowerCase() === "public" ? "PUBLIC" : qIdent(r)))
        .join(", ")
      const permissive = row.permissive === "PERMISSIVE" ? "PERMISSIVE" : "RESTRICTIVE"
      let sql = `CREATE POLICY ${qIdent(row.policyname)} ON public.${qIdent(row.tablename)} AS ${permissive} FOR ${row.cmd} TO ${roles}`
      if (row.qual) sql += ` USING (${row.qual})`
      if (row.with_check) sql += ` WITH CHECK (${row.with_check})`
      return `DO $$ BEGIN ${sql}; EXCEPTION WHEN duplicate_object THEN NULL; END $$`
    }),
  })

  phases.push({
    label: "grants",
    statements: [
      "GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role",
      "GRANT ALL ON ALL TABLES IN SCHEMA public TO postgres, service_role",
      "GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO postgres, service_role",
      // Function/table role grants are synced from production by test-db post-bootstrap.
      "REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC, anon",
      "GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO authenticated, service_role",
    ],
  })

  return phases
}

const prodEnv = parse(path.join(root, ".env.local"))
const testEnv = parse(path.join(root, ".env.test"))
const prodUrl = prodEnv.SUPABASE_DB_URL || prodEnv.DATABASE_URL
const testUrl = testEnv.TEST_DATABASE_URL || testEnv.DATABASE_URL
if (projectRefFromUrl(prodUrl) !== PRODUCTION_SUPABASE_REF) throw new Error("prod URL is not production")
if (projectRefFromUrl(testUrl) === PRODUCTION_SUPABASE_REF) throw new Error("test URL must not be production")

fs.mkdirSync(outDir, { recursive: true })

const prod = new Client({
  connectionString: prodUrl,
  ssl: { rejectUnauthorized: false },
  connectionTimeoutMillis: 30_000,
})
await prod.connect()
let phases
try {
  console.log("Building DDL phases from production (read-only)…")
  phases = await buildPhases(prod)
} finally {
  await prod.end()
}

const test = new Client({
  connectionString: testUrl,
  ssl: { rejectUnauthorized: false },
  connectionTimeoutMillis: 30_000,
})
await test.connect()
const allFailures = []
try {
  console.log("Resetting test public schema…")
  await test.query(`
    DROP SCHEMA IF EXISTS public CASCADE;
    CREATE SCHEMA public;
    GRANT ALL ON SCHEMA public TO postgres;
    GRANT ALL ON SCHEMA public TO public;
  `)

  for (const phase of phases) {
    const result = await applyStatements(test, phase.label, phase.statements)
    for (const f of result.failures) allFailures.push({ phase: phase.label, ...f })
  }

  const tables = await test.query(`
    SELECT count(*)::int AS n FROM information_schema.tables
    WHERE table_schema = 'public' AND table_type = 'BASE TABLE'
  `)
  const funcs = await test.query(`
    SELECT count(*)::int AS n FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = 'public'
  `)
  console.log(`\nDone. tables=${tables.rows[0].n} functions=${funcs.rows[0].n} total_failures=${allFailures.length}`)
} finally {
  await test.end()
}

fs.writeFileSync(
  reportPath,
  allFailures.map((f) => `[${f.phase}] ${f.msg}\n  ${f.preview}`).join("\n\n") + "\n",
)
console.log(`Failure detail: ${reportPath}`)
// Multi-pass apply: early "does not exist" / "already exists" are expected noise.
// Only failures on terminal phases (or unexpected errors) are hard.
const softPhases = new Set(["functions", "functions_pass2", "views_pass1"])
const hard = allFailures.filter((f) => {
  if (/already exists/i.test(f.msg)) return false
  if (softPhases.has(f.phase) && /does not exist/i.test(f.msg)) return false
  return true
})
console.log(`Hard failures (excl. multi-pass noise): ${hard.length}`)
process.exitCode = hard.length > 0 ? 1 : 0
